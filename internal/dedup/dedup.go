// Package dedup отвечает на единственный вопрос горячего пути: голосовали ли уже
// по этому токену.
//
// Это узкое место всей системы (architecture.md §2). Проверку нельзя ни
// батчить, ни отложить: ответ нужен до того, как голос будет принят. 250K
// синхронных round-trip'ов в секунду при потолке одной ноды Redis около 100K
// ops/sec — отсюда требование к размеру кластера.
//
// Хорошая новость: ключи шардируются сами. Токен уникален у каждого зрителя,
// хеш равномерно распределён по слотам, ручной схемы шардирования не требуется —
// нужны просто ноды.
package dedup

import (
	"context"
	"time"

	"github.com/google/uuid"
)

// Result различает три исхода, потому что третий не является ошибкой.
type Result int

const (
	// First — токен виден впервые, голос принимается.
	First Result = iota
	// Duplicate — по токену уже голосовали, 409.
	Duplicate
	// Bypassed — проверка пропущена: Redis недоступен или цепь разомкнута.
	//
	// Голос при этом ПРИНИМАЕТСЯ. fail-open выбран сознательно: ТЗ прямо
	// говорит, что дедуп слабый и обходится вручную, значит его ценность
	// заведомо ниже ценности самого результата опроса. Альтернатива —
	// отдавать 503 — уничтожила бы национальный эфир целиком
	// (architecture.md §6).
	Bypassed
)

// Checker — проверка и пометка токена одной атомарной операцией.
type Checker interface {
	// Check выполняет SET NX EX dedup:{pollID}:{token}.
	// Никогда не возвращает ошибку: недоступность выражается через Bypassed,
	// потому что вызывающий всё равно обязан принять голос.
	Check(ctx context.Context, pollID uuid.UUID, token string, ttl time.Duration) Result
}
